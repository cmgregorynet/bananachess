/** The piece shapes, ported from `PieceShapes.swift`. Normalised 0–1 and scaled into a
 *  100×100 viewBox, so the web board is drawn from the same curves as the app rather than
 *  a second artist's impression of them. */
const c = (
  x: number, y: number, c1x: number, c1y: number, c2x: number, c2y: number,
): string => `C${c1x * 100},${c1y * 100} ${c2x * 100},${c2y * 100} ${x * 100},${y * 100}`;
const m = (x: number, y: number): string => `M${x * 100},${y * 100}`;

